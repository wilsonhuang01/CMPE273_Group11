-- PostgreSQL baseline equal to SQLite schema version 12 (action R).
--
-- Column order matches the SQLite tables exactly: the repository uses positional
-- INSERT ... VALUES statements. Every table ends with a hidden "rowid" identity column
-- that reproduces SQLite's insertion-ordered rowid for ORDER BY rowid. Positional
-- inserts omit it, and the row adapter drops it from SELECT * results.
-- INTEGER becomes BIGINT (SQLite integers are 64-bit) and BLOB becomes BYTEA.
CREATE TABLE tasks (
    task_id TEXT PRIMARY KEY,
    submission BYTEA NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('accepted', 'running', 'completed', 'failed')),
    revision BIGINT NOT NULL DEFAULT 0,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE task_history (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    status TEXT NOT NULL,
    revision BIGINT NOT NULL,
    reason TEXT NOT NULL,
    recorded_at_unix_ms BIGINT NOT NULL,
    UNIQUE(task_id, revision),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE messages (
    message_id TEXT PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    kind TEXT NOT NULL,
    payload BYTEA NOT NULL,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE requests (
    proposal_id TEXT PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    payload BYTEA NOT NULL,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE proposals (
    proposal_id TEXT PRIMARY KEY REFERENCES requests(proposal_id),
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    payload BYTEA NOT NULL,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE jobs (
    job_id TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    payload BYTEA NOT NULL,
    PRIMARY KEY(job_id, attempt),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE results (
    job_id TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    payload BYTEA NOT NULL,
    PRIMARY KEY(job_id, attempt),
    FOREIGN KEY(job_id, attempt) REFERENCES jobs(job_id, attempt),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE artifacts (
    key TEXT PRIMARY KEY,
    sha256 TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE task_artifacts (
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    key TEXT NOT NULL REFERENCES artifacts(key),
    kind TEXT NOT NULL,
    owner_id TEXT NOT NULL,
    PRIMARY KEY(task_id, key, kind, owner_id),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE decisions (
    task_id TEXT PRIMARY KEY REFERENCES tasks(task_id),
    job_id TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    reason TEXT NOT NULL,
    scores_json TEXT NOT NULL,
    recorded_at_unix_ms BIGINT NOT NULL,
    FOREIGN KEY(job_id, attempt) REFERENCES results(job_id, attempt),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE INDEX requests_task ON requests(task_id);
CREATE INDEX proposals_task ON proposals(task_id);
CREATE INDEX jobs_task ON jobs(task_id);
CREATE INDEX results_task ON results(task_id);

CREATE TABLE benchmark_runs (
    run_id TEXT PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    job_id TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    source_sha256 TEXT NOT NULL,
    report_key TEXT NOT NULL REFERENCES artifacts(key),
    qualified BIGINT NOT NULL CHECK(qualified IN (0, 1)),
    candidate_invalid BIGINT NOT NULL CHECK(candidate_invalid IN (0, 1)),
    recorded_at_unix_ms BIGINT NOT NULL,
    FOREIGN KEY(job_id, attempt) REFERENCES results(job_id, attempt),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE INDEX benchmark_task ON benchmark_runs(task_id, job_id, attempt);

CREATE TABLE pipeline_runs (
    task_id TEXT PRIMARY KEY REFERENCES tasks(task_id),
    proposal_id TEXT NOT NULL UNIQUE REFERENCES proposals(proposal_id),
    configuration_json TEXT NOT NULL,
    phase TEXT NOT NULL CHECK(phase IN ('queued', 'published', 'verifying', 'benchmarking', 'completed')),
    published BIGINT NOT NULL DEFAULT 0 CHECK(published IN (0, 1)),
    report_key TEXT REFERENCES artifacts(key),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE agent_iterations (
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    role BIGINT NOT NULL,
    iteration BIGINT NOT NULL,
    operation_id TEXT NOT NULL,
    input_key TEXT NOT NULL REFERENCES artifacts(key),
    output_key TEXT REFERENCES artifacts(key),
    status TEXT NOT NULL CHECK(status IN ('started', 'completed', 'failed')),
    PRIMARY KEY(task_id, role, iteration),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE INDEX agent_operation ON agent_iterations(task_id, role, operation_id);

CREATE TABLE selection_sessions (
    task_id TEXT PRIMARY KEY REFERENCES tasks(task_id),
    policy_key TEXT NOT NULL REFERENCES artifacts(key),
    cohort_json TEXT NOT NULL,
    outcome_key TEXT REFERENCES artifacts(key),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE selection_progress (
    task_id TEXT NOT NULL REFERENCES selection_sessions(task_id),
    proposal_id TEXT NOT NULL REFERENCES requests(proposal_id),
    status TEXT NOT NULL CHECK(status IN ('evaluated', 'generation_failed', 'assessment_failed')),
    evidence_key TEXT NOT NULL REFERENCES artifacts(key),
    PRIMARY KEY(task_id, proposal_id),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE recovery_workers (
    worker_id TEXT PRIMARY KEY,
    incarnation_id TEXT NOT NULL,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    sequence BIGINT NOT NULL DEFAULT 0,
    state TEXT NOT NULL CHECK(state IN ('idle', 'busy', 'quarantined')),
    last_seen_ms BIGINT NOT NULL,
    quarantine_until_ms BIGINT NOT NULL DEFAULT 0,
    current_job_id TEXT,
    heartbeat BYTEA,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE recovery_jobs (
    scope TEXT NOT NULL DEFAULT 'evaluate',
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    proposal_id TEXT NOT NULL REFERENCES proposals(proposal_id),
    job_id TEXT NOT NULL UNIQUE,
    policy_key TEXT NOT NULL REFERENCES artifacts(key),
    base_context_json TEXT NOT NULL,
    execution_context_json TEXT,
    state TEXT NOT NULL CHECK(state IN ('pending', 'leased', 'backoff', 'completed', 'quarantined', 'exhausted')),
    attempt BIGINT NOT NULL DEFAULT 0,
    fence BIGINT NOT NULL DEFAULT 0,
    worker_id TEXT REFERENCES recovery_workers(worker_id),
    incarnation_id TEXT,
    lease_token TEXT,
    lease_expires_ms BIGINT,
    deadline_ms BIGINT,
    available_at_ms BIGINT NOT NULL DEFAULT 0,
    mode TEXT NOT NULL DEFAULT 'evaluate',
    crash_json TEXT,
    cleanup_token TEXT,
    outcome_key TEXT REFERENCES artifacts(key),
    PRIMARY KEY(task_id, proposal_id, scope),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE recovery_attempts (
    job_id TEXT NOT NULL REFERENCES recovery_jobs(job_id),
    attempt BIGINT NOT NULL,
    worker_id TEXT,
    lease_token TEXT,
    fence BIGINT NOT NULL,
    started_ms BIGINT NOT NULL,
    finished_ms BIGINT,
    status TEXT NOT NULL,
    evidence_key TEXT REFERENCES artifacts(key),
    PRIMARY KEY(job_id, attempt),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE recovery_blacklist (
    key TEXT PRIMARY KEY,
    record_key TEXT NOT NULL REFERENCES artifacts(key),
    expires_ms BIGINT NOT NULL,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE recovery_outbox (
    event_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES recovery_jobs(job_id),
    kind TEXT NOT NULL CHECK(kind IN ('retry', 'deadletter', 'blacklist')),
    payload_json TEXT NOT NULL,
    sent_ms BIGINT,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE submission_executions (
    task_id TEXT PRIMARY KEY REFERENCES tasks(task_id),
    configuration_json TEXT NOT NULL,
    stage TEXT NOT NULL DEFAULT 'queued',
    attempts BIGINT NOT NULL DEFAULT 0,
    available_at_ms BIGINT NOT NULL DEFAULT 0,
    error_code TEXT,
    finished BIGINT NOT NULL DEFAULT 0 CHECK(finished IN (0, 1)),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE fleet_workers (
    worker_id TEXT PRIMARY KEY,
    incarnation_id TEXT NOT NULL,
    secret_hash TEXT NOT NULL,
    profile_json TEXT NOT NULL,
    engine_id TEXT NOT NULL,
    sequence BIGINT NOT NULL DEFAULT 0,
    last_seen_ms BIGINT NOT NULL,
    active_job TEXT,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE fleet_jobs (
    job_id TEXT PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    worker_id TEXT NOT NULL,
    incarnation_id TEXT NOT NULL,
    engine_id TEXT NOT NULL,
    parent_token TEXT,
    input_key TEXT NOT NULL REFERENCES artifacts(key),
    operation TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending',
    fence BIGINT NOT NULL DEFAULT 1,
    token TEXT NOT NULL,
    expires_ms BIGINT,
    deadline_ms BIGINT NOT NULL,
    published_ms BIGINT NOT NULL DEFAULT 0,
    result_key TEXT REFERENCES artifacts(key),
    error TEXT,
    window_token TEXT,
    reservation_mib BIGINT NOT NULL DEFAULT 128,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE INDEX fleet_pending ON fleet_jobs(state, deadline_ms);

CREATE TABLE cohort_runs (
    task_id TEXT PRIMARY KEY REFERENCES selection_sessions(task_id),
    workers BIGINT NOT NULL,
    reservation_mib BIGINT NOT NULL,
    state TEXT NOT NULL DEFAULT 'preparing'
        CHECK(state IN ('preparing','measuring','completed','cancelling','cancelled')),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE cohort_work (
    task_id TEXT NOT NULL REFERENCES cohort_runs(task_id),
    proposal_id TEXT NOT NULL REFERENCES requests(proposal_id),
    state TEXT NOT NULL CHECK(state IN ('pending','preparing','ready','completed','cancelled')),
    PRIMARY KEY(task_id, proposal_id),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE measurement_windows (
    token TEXT PRIMARY KEY,
    engine_id TEXT NOT NULL,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    parent_token TEXT,
    state TEXT NOT NULL CHECK(state IN ('waiting','active','draining','released')),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE measurement_claims (
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    proposal_id TEXT NOT NULL REFERENCES proposals(proposal_id),
    job_id TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    plan_key TEXT NOT NULL REFERENCES artifacts(key),
    lease_token TEXT,
    attempts BIGINT NOT NULL DEFAULT 1,
    state TEXT NOT NULL CHECK(state IN ('running','retryable','completed')),
    PRIMARY KEY(task_id,proposal_id),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE agent_rpc_calls (
    call_id TEXT PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(task_id),
    role BIGINT NOT NULL,
    operation_id TEXT NOT NULL,
    request_sha256 TEXT NOT NULL,
    status TEXT NOT NULL,
    receipt_key TEXT NOT NULL REFERENCES artifacts(key),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE debate_runs (
    task_id TEXT PRIMARY KEY REFERENCES selection_sessions(task_id),
    policy_key TEXT NOT NULL REFERENCES artifacts(key),
    started_ms BIGINT NOT NULL,
    deadline_ms BIGINT NOT NULL,
    calls BIGINT NOT NULL DEFAULT 0,
    final_proposal_id TEXT,
    final_state TEXT,
    final_report_key TEXT REFERENCES artifacts(key),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE debate_slots (
    task_id TEXT NOT NULL REFERENCES debate_runs(task_id),
    proposal_id TEXT PRIMARY KEY REFERENCES requests(proposal_id),
    round_number BIGINT NOT NULL,
    parent_id TEXT,
    context_key TEXT REFERENCES artifacts(key),
    reason TEXT,
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
);
CREATE TABLE debate_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES debate_runs(task_id),
    proposal_id TEXT,
    event TEXT NOT NULL,
    record_key TEXT NOT NULL REFERENCES artifacts(key),
    UNIQUE(task_id, proposal_id, event),
    rowid BIGINT GENERATED ALWAYS AS IDENTITY
)
